/**
 * One architecture only in the APK: arm64.
 *
 * React Native packs the native libraries for four architectures: two
 * real ones (arm) and two for the emulators on a PC (x86). On a phone
 * those two are dead weight, and Android has to check and unpack them
 * at install time all the same: they are the thirty seconds of
 * "preparing app" on a mid-range phone.
 *
 * armeabi-v7a too, which had stayed "for the older phones", is of use
 * to nobody here: 32-bit phones stopped coming out ten years ago, and
 * this app wants a camera, WebRTC and Android 8 in any case. Dropping
 * it means an APK half the size - one that has to be sent to the other
 * person by message, which is no detail - and less code mapped into
 * memory on a phone that has little of it.
 *
 * Anybody wanting an emulator, or a 32-bit phone, adds their
 * architecture here and builds again.
 *
 * It lives in a script because android/ is generated by bootstrap.sh
 * and not under version control: editing it by hand would mean losing
 * the change at the first regeneration.
 */
const fs = require('fs');
const path = require('path');

/**
 * The list React Native uses to BUILD its libraries.
 *
 * It is another knob on the same side: `abiFilters` decides what ends
 * up in the APK, this one decides what gets built. Leaving it wide
 * builds libraries for architectures that are then thrown away: build
 * time given away.
 */
function narrowProperties() {
  const prop = path.join(__dirname, '..', 'android', 'gradle.properties');
  if (!fs.existsSync(prop)) return;
  const text = fs.readFileSync(prop, 'utf8');
  const line = /^reactNativeArchitectures=.*$/m;
  if (!line.test(text)) return;
  if (/^reactNativeArchitectures=arm64-v8a$/m.test(text)) return;
  fs.writeFileSync(prop, text.replace(line, 'reactNativeArchitectures=arm64-v8a'));
  console.log('architectures to build: arm64-v8a only');
}

const file = path.join(__dirname, '..', 'android', 'app', 'build.gradle');

/**
 * The release build signed with a key of its own, when there is one.
 *
 * The template signs the release with the DEBUG keystore - password
 * "android", the same on every React Native project on earth - which
 * for an app handed from one phone to the other was indifferent, and
 * for an app anybody can download is not: whoever holds that key can
 * sign an "update" Android accepts as ours. The real key lives outside
 * the repository, and Gradle learns of it from ~/.gradle/gradle.properties:
 *
 *   DUETTO_STORE_FILE=/home/you/.config/duetto/release.keystore
 *   DUETTO_STORE_PASSWORD=...
 *   DUETTO_KEY_ALIAS=duetto
 *   DUETTO_KEY_PASSWORD=...
 *
 * Without those properties - somebody building from a fresh clone - the
 * release falls back to the debug key as before, so the build never
 * breaks: it is just not ours.
 */
function signRelease() {
  let g = fs.readFileSync(file, 'utf8');
  if (g.includes('DUETTO_STORE_FILE')) return;
  const marker = /(    signingConfigs \{\n        debug \{[\s\S]*?\n        \}\n)(    \})/;
  const swap = 'signingConfig signingConfigs.debug\n            minifyEnabled';
  if (!marker.test(g) || !g.includes(swap)) {
    console.error('signing block not found in build.gradle: touching nothing');
    return;
  }
  const release = `        release {
            // The real key, from ~/.gradle/gradle.properties; see
            // patch-android-gradle.js. Absent, the debug one stands -
            // put here, inside the block, so that the release build
            // type below can name signingConfigs.release plainly:
            // F-Droid strips signing blocks and that plain line before
            // building with its own key, and an expression escaped it.
            if (project.hasProperty('DUETTO_STORE_FILE')) {
                storeFile file(DUETTO_STORE_FILE)
                storePassword DUETTO_STORE_PASSWORD
                keyAlias DUETTO_KEY_ALIAS
                keyPassword DUETTO_KEY_PASSWORD
            } else {
                storeFile file('debug.keystore')
                storePassword 'android'
                keyAlias 'androiddebugkey'
                keyPassword 'android'
            }
        }
`;
  g = g.replace(marker, `$1${release}$2`);
  g = g.replace(
    swap,
    'signingConfig signingConfigs.release\n            minifyEnabled',
  );
  fs.writeFileSync(file, g);
  console.log('release signing: our own key when ~/.gradle/gradle.properties names one');
}
if (!fs.existsSync(file)) {
  console.log('build.gradle not generated yet: nothing to do');
  process.exit(0);
}

narrowProperties();
signRelease();

let gradle = fs.readFileSync(file, 'utf8');

const WANTED = "abiFilters 'arm64-v8a'";
/** The right line is the one that ends there: no commas, nothing else. */
const ALREADY_FINE = /abiFilters\s+'arm64-v8a'\s*$/m;

if (ALREADY_FINE.test(gradle)) {
  console.log('architectures already filtered: arm64-v8a only');
  process.exit(0);
}

// A wider filter, written by an earlier version of this script: it is
// narrowed instead of being left as it is.
if (gradle.includes('abiFilters')) {
  gradle = gradle.replace(/abiFilters[^\n]*/, WANTED);
  fs.writeFileSync(file, gradle);
  console.log('architectures narrowed: arm64-v8a only');
  process.exit(0);
}

const block = `        ndk {
            // One only: the x86 emulators and the 32-bit phones
            // doubled the APK. See patch-android-gradle.js
            ${WANTED}
        }
`;

// It hooks onto the end of defaultConfig, which every RN project has.
const marker = /(defaultConfig\s*\{[\s\S]*?)(\n    \})/;
if (!marker.test(gradle)) {
  console.error('defaultConfig not found in build.gradle: touching nothing');
  process.exit(1);
}

gradle = gradle.replace(marker, `$1\n${block}$2`);
fs.writeFileSync(file, gradle);
console.log('architectures filtered: arm64-v8a only');
